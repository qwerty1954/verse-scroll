/// <reference types="node" />
// Builds src/data/weights.ts, the Random-mode weight of every verse, from the OpenBible.info
// cross-reference data (https://www.openbible.info/labs/cross-references/, CC-BY).
//
// Usage: node scripts/build-weights.ts path/to/cross_references.txt
//
// Votes for a verse = the votes on every cross-reference pair it's part of, on either side,
// with negative votes counted as 0. A range like "Gen.1.1-Gen.1.3" credits its first verse.
// Weight = 1 + ln(1 + votes), stored as tenths so the file holds small whole numbers.
// The output contains verse positions and numbers only, no Scripture text.
import { readFileSync, writeFileSync } from 'node:fs';
import { VERSE_COUNTS } from '../src/data/verseCounts.ts';

const OSIS = [
  'Gen', 'Exod', 'Lev', 'Num', 'Deut', 'Josh', 'Judg', 'Ruth', '1Sam', '2Sam', '1Kgs', '2Kgs',
  '1Chr', '2Chr', 'Ezra', 'Neh', 'Esth', 'Job', 'Ps', 'Prov', 'Eccl', 'Song', 'Isa', 'Jer', 'Lam',
  'Ezek', 'Dan', 'Hos', 'Joel', 'Amos', 'Obad', 'Jonah', 'Mic', 'Nah', 'Hab', 'Zeph', 'Hag', 'Zech',
  'Mal', 'Matt', 'Mark', 'Luke', 'John', 'Acts', 'Rom', '1Cor', '2Cor', 'Gal', 'Eph', 'Phil', 'Col',
  '1Thess', '2Thess', '1Tim', '2Tim', 'Titus', 'Phlm', 'Heb', 'Jas', '1Pet', '2Pet', '1John',
  '2John', '3John', 'Jude', 'Rev',
];
const bookIndex = new Map(OSIS.map((code, i) => [code, i]));

const input = process.argv[2];
if (!input) {
  console.error('Usage: node scripts/build-weights.ts path/to/cross_references.txt');
  process.exit(1);
}

// votes[book][chapter][verse], 0-based, sized from the verse counts.
const votes = VERSE_COUNTS.map((chapters) => chapters.map((n) => new Array<number>(n).fill(0)));

let pairs = 0;
let skipped = 0;
function credit(ref: string, amount: number) {
  const [code, ch, vs] = ref.split('-')[0].split('.');
  const book = bookIndex.get(code);
  const row = book === undefined ? undefined : votes[book]?.[Number(ch) - 1];
  const verse = Number(vs) - 1;
  if (!row || !(verse >= 0 && verse < row.length)) {
    skipped++;
    return;
  }
  row[verse] += amount;
}

const lines = readFileSync(input, 'utf8').split(/\r?\n/);
for (const line of lines.slice(1)) {
  if (!line.trim()) continue;
  const [from, to, raw] = line.split('\t');
  const amount = Math.max(0, Number(raw) || 0);
  credit(from, amount);
  credit(to, amount);
  pairs++;
}

const tenths = votes.map((chapters) =>
  chapters.map((row) => row.map((v) => Math.round((1 + Math.log(1 + v)) * 10))),
);

const body = tenths
  .map((chapters, i) => `  /* ${OSIS[i]} */ ${JSON.stringify(chapters)}`)
  .join(',\n');
writeFileSync(
  new URL('../src/data/weights.ts', import.meta.url),
  `// Random-mode weight of each verse in tenths: WEIGHTS[book][chapter][verse], all 0-based.
// Generated by scripts/build-weights.ts from OpenBible.info cross-reference data
// (https://www.openbible.info/labs/cross-references/), licensed CC-BY. No Scripture text.

export const WEIGHTS: number[][][] = [
${body},
];
`,
);

const all = tenths.flat(2);
console.log(
  `pairs ${pairs}, unmatched refs ${skipped}, verses ${all.length}, ` +
    `weight range ${Math.min(...all) / 10}-${Math.max(...all) / 10}`,
);
